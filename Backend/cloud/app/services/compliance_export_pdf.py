"""Render a compliance audit pack as a PDF. Pure: pack in, bytes out.

The document a reviewer reads and signs. Order follows how an audit is read:
who and what was assessed and how fresh it is, the headline per framework,
what to fix first, then each framework control by control with the evidence
behind every failure, the exceptions register, the gaps (not evaluated, not
applicable, incomplete collection), the method, and a sign-off block.

Every page carries the pack ID, so a printed page can be traced back to the
exact pack (and its SHA-256) it came from. Styling is the client report's —
same palette, fonts and table style — so the two read as one product.
"""
