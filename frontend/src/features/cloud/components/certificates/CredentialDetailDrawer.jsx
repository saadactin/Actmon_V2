import { useMemo } from 'react';
import { useNavigate } from 'react-router-dom';
import Badge from '@/components/ui/Badge';
import Button from '@/components/ui/Button';
import CopyButton from '@/components/ui/CopyButton';
import Drawer from '@/components/ui/Drawer';
import Icon from '@/components/ui/Icon';
import { EmptyState } from '@/components/ui/Table';
import { InlineLoading } from '@/components/ui/Loading';
import { useCredentialFindings } from '../../hooks/useCertificates';
import RefreshAllButton from '../refresh/RefreshAllButton';
import { credentialGuidance } from '../../utils/credentialGuidance';
import { accountRoute, bucketMeta, daysLeftLabel, kindMeta } from '../../utils/clientModel';
import {
  formatDateTime, providerLabel, severityTone, statusMeta,
} from '../../utils/securityModel';

// Static class names per tone: a class built by interpolation is never
// generated by Tailwind, so the box would render unstyled.
const TONE_BOX = {
  danger: 'border-danger-soft bg-danger-soft text-danger-fg',
  warning: 'border-warning-soft bg-warning-soft text-warning-fg',
  info: 'border-info-soft bg-info-soft text-info-fg',
  neutral: 'border-border bg-sunken text-fg',
};

// Where the usage above came from (the collectors' details.usage_source).
const USAGE_SOURCE = {
  live: 'the load balancer itself',
  'last discovery': 'the last discovery scan (the load balancer could not be read)',
};

// Detail keys shown in their own section, so the generic list skips them.
const SHOWN_DETAILS = new Set(['usage_source', 'store']);

const DETAIL_LABEL = {
  type: 'ACM type',
  renewal_eligibility: 'Renewal eligibility',
  exported: 'Exported',
  path: 'IAM path',
  uploaded: 'Uploaded',
  thumbprint: 'Thumbprint',
  key_vault_id: 'Key Vault source',
  server_farm_id: 'App Service plan',
  resource_group: 'Resource group',
  config_type: 'Certificate type',
  compartment_id: 'Compartment',
  stages: 'Version stages',
  owning_service: 'Managed by',
  last_accessed: 'Last read',
  created: 'Created',
  primary_region: 'Primary region',
  recovery_level: 'Recovery level',
  content_type: 'Content type',
  rotation_status: 'Rotation status',
  issuer_name: 'Issuer (policy)',
};

const humanize = (key) => DETAIL_LABEL[key] || key.replace(/_/g, ' ').replace(/^\w/, (c) => c.toUpperCase());

function valueText(v) {
  if (v === null || v === undefined || v === '') return null;
  if (Array.isArray(v)) return v.length ? v.join(', ') : null;
  if (typeof v === 'boolean') return v ? 'Yes' : 'No';
  if (typeof v === 'object') return JSON.stringify(v);
  return String(v);
}

function Section({ title, icon, children, action }) {
  return (
    <section className="space-y-2">
      <div className="flex items-center gap-2">
        {icon && <Icon name={icon} size={14} className="text-subtle" />}
        <h3 className="text-[11px] font-bold uppercase tracking-[0.07em] text-subtle">{title}</h3>
        <span className="h-px flex-1 bg-border" />
        {action}
      </div>
      {children}
    </section>
  );
}

function Row({ label, children, mono = false, copy }) {
  if (children === null || children === undefined || children === '') return null;
  return (
    <div className="grid grid-cols-[140px_minmax(0,1fr)] gap-3 py-1 text-[12px]">
      <span className="text-muted">{label}</span>
      <div className="flex min-w-0 items-start gap-2">
        <span className={`min-w-0 break-all text-fg ${mono ? 'font-mono text-[11px]' : ''}`}>{children}</span>
        {copy && <CopyButton text={copy} label="Copy" size="sm" variant="ghost" />}
      </div>
    </div>
  );
}

function renewalText(o) {
  if (o.kind !== 'CERTIFICATE') return null;
  if (o.managed_renewal === true) return `Renews automatically${o.renewal_status ? ` · ${o.renewal_status}` : ''}`;
  if (o.managed_renewal === false) return 'Manual — nothing renews it';
  return 'Not reported by the provider';
}

function rotationText(o) {
  if (o.kind === 'CERTIFICATE') return null;
  if (o.rotation_enabled === true) {
    return `On${o.rotation_interval_days ? `, every ${o.rotation_interval_days} days` : ''}`;
  }
  if (o.rotation_enabled === false) return 'Off';
  return null;
}

/** One step of "What you can do". */
function Step({ step, onAction }) {
  return (
    <li className="rounded-control border border-border p-3">
      <div className="flex items-start gap-2.5">
        <span className="grid h-5 w-5 shrink-0 place-items-center rounded-full bg-accent-soft text-[11px] font-bold text-accent-text">
          {step.n}
        </span>
        <div className="min-w-0 flex-1 space-y-1.5">
          <p className="text-[13px] font-semibold text-fg">{step.title}</p>
          {step.body && <p className="text-[12px] leading-relaxed text-muted">{step.body}</p>}
          {step.console && (
            <p className="flex items-start gap-1.5 text-[12px] text-fg">
              <Icon name="external" size={12} className="mt-0.5 shrink-0 text-subtle" />
              <span>{step.console}</span>
            </p>
          )}
          {step.command && (
            <div className="relative">
              <pre className="max-h-48 overflow-auto whitespace-pre-wrap break-all rounded-control bg-sunken p-2.5 pr-16 font-mono text-[11px] leading-relaxed text-fg">
                {step.command}
              </pre>
              <div className="absolute top-1.5 right-1.5">
                <CopyButton text={step.command} label="Copy" size="sm" />
              </div>
            </div>
          )}
          {step.caution && (
            <p className="flex items-start gap-1.5 text-[11px] leading-relaxed text-warning-fg">
              <Icon name="alert" size={12} className="mt-0.5 shrink-0" />
              <span>{step.caution}</span>
            </p>
          )}
          {step.action === 'alerts' && (
            <Button size="sm" icon="bell" onClick={() => onAction?.('alerts')}>Open Alerts</Button>
          )}
        </div>
      </div>
    </li>
  );
}

/**
 * Everything known about one certificate, secret or key, and what to do
 * about it. Opened by clicking a row in any certificate table.
 *
 * `object` is the live row (re-read after a collection), `missing` is true
 * when the row that was open is no longer in the inventory.
 */
export default function CredentialDetailDrawer({ object: o, missing = false, onClose, onOpenFinding }) {
  const navigate = useNavigate();
  const open = !!o || missing;
  const guidance = useMemo(() => credentialGuidance(o), [o]);
  const { data: found, isLoading: loadingFindings } = useCredentialFindings(
    o?.account_id, o?.object_key, !!o,
  );

  if (!open) return null;

  const route = o ? accountRoute(o.provider, o.account_id) : null;
  const kind = kindMeta(o?.kind);
  const bucket = bucketMeta(o?.bucket);
  // Matched again here, exactly: a backend older than the resource_key filter
  // ignores the parameter and would return the account's findings at large.
  const findings = (found?.findings || []).filter((f) => f.resource_key === o?.object_key);

  const openFinding = (fingerprint) => {
    if (onOpenFinding) {
      onClose?.();
      onOpenFinding(fingerprint);
    } else if (route) {
      navigate(`${route}/security?view=findings&finding=${encodeURIComponent(fingerprint)}`);
    }
  };
  const onAction = (action) => {
    if (action === 'alerts' && route) navigate(`${route}/alerts`);
  };
  const details = Object.entries(o?.details || {})
    .filter(([k, v]) => !SHOWN_DETAILS.has(k) && valueText(v) !== null);

  return (
    <Drawer
      open={open}
      onClose={onClose}
      title={o ? (o.name || o.object_key) : 'No longer in this list'}
      subtitle={o ? [kind.label, o.source_label, o.account_name].filter(Boolean).join(' · ') : undefined}
      icon={kind.icon}
      width={680}
      footer={o && (
        <div className="flex items-center justify-between gap-3">
          {/* The same Refresh all as the account header — it was "Re-check
              account" here, a fourth name for re-reading the provider. */}
          <p className="text-[11px] leading-snug text-muted">
            Fixed it? Refresh all re-reads the whole account — every certificate and secret
            store included — and re-assesses. It takes as long as a full scan.
          </p>
          <div className="flex shrink-0 items-center gap-2">
            <RefreshAllButton accountId={o.account_id} variant="secondary" />
            <Button variant="primary" onClick={onClose}>Close</Button>
          </div>
        </div>
      )}
    >
      {!o ? (
        <EmptyState
          icon="lock"
          title="No longer in this list"
          body="After the last re-read, the item that was open is not in this list: it was deleted or renamed, replaced by a renewal with a new identifier, or no longer matches the list's filter."
        />
      ) : (
        <div className="space-y-6">
          {/* Where it stands, in one sentence. */}
          <div className={`rounded-card border p-3.5 ${TONE_BOX[guidance.headline.tone] || TONE_BOX.neutral}`}>
            <div className="flex flex-wrap items-center gap-2">
              <Badge tone={bucket.tone}>{bucket.label}</Badge>
              {o.enabled === false && <Badge tone="outline">Disabled</Badge>}
              <span className="text-[12px] font-semibold">
                {o.expires_at ? `${formatDateTime(o.expires_at)} · ${daysLeftLabel(o.days_left)}` : 'No expiry date'}
              </span>
            </div>
            <p className="mt-1.5 text-[13px] leading-relaxed">{guidance.headline.text}</p>
          </div>

          <Section title="What you can do" icon="wrench">
            {!guidance.guided ? (
              <p className="text-[12px] text-muted">No specific steps are written for this store yet.</p>
            ) : guidance.steps.length === 0 ? (
              <p className="text-[12px] text-muted">No action is due for this item right now.</p>
            ) : (
              <ol className="space-y-2.5">
                {guidance.steps.map((step) => <Step key={step.id} step={step} onAction={onAction} />)}
              </ol>
            )}
            {guidance.steps.some((s) => s.command) && (
              <p className="text-[11px] leading-relaxed text-subtle">
                Commands carry this item&apos;s real identifiers. Replace the &lt;…&gt; placeholders and the
                file names with your own, and review before running — they change live resources.
              </p>
            )}
          </Section>

          <Section title="Where it is used" icon="link">
            <p className={`text-[12px] ${guidance.usage.known ? 'text-fg' : 'text-warning-fg'}`}>
              {guidance.usage.text}
            </p>
            {guidance.usage.items.length > 0 && (
              <ul className="space-y-1">
                {guidance.usage.items.map((u) => (
                  <li key={u} className="flex items-start gap-2 rounded-control bg-sunken px-2.5 py-1.5 font-mono text-[11px] text-fg">
                    <Icon name="link" size={12} className="mt-0.5 shrink-0 text-subtle" />
                    <span className="break-all">{u}</span>
                  </li>
                ))}
              </ul>
            )}
            {o.details?.usage_source && (
              <p className="text-[11px] text-subtle">
                Read from {USAGE_SOURCE[o.details.usage_source] || o.details.usage_source} ·
                collected {formatDateTime(o.last_seen_at)}
              </p>
            )}
          </Section>

          <Section
            title="Security findings"
            icon="shield"
            action={findings.length > 0 && <Badge tone="neutral" size="xs">{findings.length}</Badge>}
          >
            {loadingFindings ? <InlineLoading label="Loading findings…" /> : findings.length === 0 ? (
              <p className="text-[12px] text-muted">
                No open finding for this item. Findings come from the latest assessment of the account.
              </p>
            ) : (
              <ul className="space-y-1.5">
                {findings.map((f) => {
                  const st = statusMeta(f.status);
                  return (
                    <li key={f.fingerprint}>
                      <button
                        type="button"
                        onClick={() => openFinding(f.fingerprint)}
                        className="flex w-full items-center gap-2 rounded-control border border-border px-2.5 py-2 text-left transition-colors hover:border-strong"
                      >
                        <Badge tone={severityTone(f.severity)} size="xs">{f.severity}</Badge>
                        <span className="min-w-0 flex-1 truncate-safe text-[12px] font-medium text-fg">{f.title}</span>
                        <Badge tone={st.tone} size="xs">{st.label}</Badge>
                        <Icon name="chevron-right" size={14} className="shrink-0 text-subtle" />
                      </button>
                    </li>
                  );
                })}
              </ul>
            )}
            {findings.length > 0 && (
              <p className="text-[11px] text-subtle">
                Open a finding to mark it in progress, suppress it, or accept the risk — the last two
                ask for a reason, so the decision is on record.
              </p>
            )}
          </Section>

          <Section title="Certificate details" icon="list">
            <div className="divide-y divide-border">
              <Row label="Expires">{o.expires_at ? formatDateTime(o.expires_at) : 'No expiry date set'}</Row>
              <Row label="Valid from">{o.not_before ? formatDateTime(o.not_before) : null}</Row>
              <Row label="Subject">{o.subject}</Row>
              <Row label="Issuer">{o.issuer}</Row>
              <Row label="Domains">
                {(o.dns_names || []).length ? (
                  <span className="flex flex-wrap gap-1">
                    {o.dns_names.slice(0, 30).map((d) => <Badge key={d} tone="outline" size="xs">{d}</Badge>)}
                    {o.dns_names.length > 30 && <span className="text-subtle">+{o.dns_names.length - 30} more</span>}
                  </span>
                ) : null}
              </Row>
              <Row label="Key">{o.key_algorithm}</Row>
              <Row label="Renewal">{renewalText(o)}</Row>
              <Row label="Rotation">{rotationText(o)}</Row>
              <Row label="Last rotated">{o.last_rotated_at ? formatDateTime(o.last_rotated_at) : null}</Row>
              <Row label="Next rotation">{o.next_rotation_at ? formatDateTime(o.next_rotation_at) : null}</Row>
              <Row label="Provider status">{o.status}</Row>
            </div>
          </Section>

          <Section
            title="Location"
            icon="cloud"
            action={guidance.portal && (
              <a
                href={guidance.portal}
                target="_blank"
                rel="noreferrer"
                className="inline-flex items-center gap-1 text-[12px] font-semibold text-accent-text hover:underline"
              >
                Open in Azure portal <Icon name="external" size={12} />
              </a>
            )}
          >
            <div className="divide-y divide-border">
              <Row label="Account">{o.account_name ? `${o.account_name} · ${providerLabel(o.provider)}` : providerLabel(o.provider)}</Row>
              <Row label="Store">{o.source_label || o.source}</Row>
              <Row label="In">{o.container_name}</Row>
              <Row label="Region">{o.region}</Row>
              <Row label="Identifier" mono copy={o.object_key}>{o.object_key}</Row>
              <Row label="Container ID" mono copy={o.container_key}>{o.container_key}</Row>
            </div>
          </Section>

          {details.length > 0 && (
            <Section title="Provider details" icon="info">
              <div className="divide-y divide-border">
                {details.map(([k, v]) => (
                  <Row key={k} label={humanize(k)} mono={/_id$|thumbprint|compartment/.test(k)}>
                    {valueText(v)}
                  </Row>
                ))}
              </div>
            </Section>
          )}

          <Section title="Seen by Actmon" icon="history">
            <div className="divide-y divide-border">
              <Row label="First seen">{formatDateTime(o.first_seen_at)}</Row>
              <Row label="Last collected">{formatDateTime(o.last_seen_at)}</Row>
            </div>
          </Section>
        </div>
      )}
    </Drawer>
  );
}
